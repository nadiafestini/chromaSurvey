export const t = (lang: Lang, key: StringKey): string => STRINGS[lang][key];

export function pickLang(cookie: string | undefined, acceptLanguage: string | undefined): Lang {
  if (cookie === "it" || cookie === "en") return cookie;
  return (acceptLanguage ?? "").toLowerCase().startsWith("it") ? "it" : "en";
}
